# -*- coding: utf-8 -*-

"""
``agent-app web-env``: the web app's settings, from the deployed stack's
outputs. None is a secret (a public client ID, a domain, a runtime ARN): the
web tier holds no credential, and the agent's JWT authorizer is what decides
who gets in.

Written to ``.env.local`` (git-ignored; Next.js reads it in development) and
printed for the Vercel project's environment variables.
"""

from pathlib import Path

from ..paths import path_enum
from .deployed_check import STACK_NAME

PATH_ENV_LOCAL = path_enum.dir_project_root / ".env.local"

#: Web setting -> the stack output it comes from.
WEB_ENV_OUTPUTS = {
    "COGNITO_DOMAIN": "CognitoDomain",
    "COGNITO_CLIENT_ID": "WebClientId",
    "AGENT_RUNTIME_ARN": "AgentRuntimeArn",
}


def web_env(outputs: dict[str, str]) -> dict[str, str]:
    """
    :raises KeyError: naming the stack output that is missing.
    """
    missing = [o for o in WEB_ENV_OUTPUTS.values() if o not in outputs]
    if missing:
        raise KeyError(f"The stack {STACK_NAME} has no output {', '.join(missing)}; deploy it first")
    return {name: outputs[output] for name, output in WEB_ENV_OUTPUTS.items()}


def render_env_file(values: dict[str, str]) -> str:
    lines = ["# Generated by `agent-app web-env` from the deployed stack; not secret, not committed."]
    lines += [f'{name}="{value}"' for name, value in values.items()]
    return "\n".join(lines) + "\n"


def write_env_local(values: dict[str, str], path: Path = PATH_ENV_LOCAL) -> None:
    path.write_text(render_env_file(values), encoding="utf-8")
