# -*- coding: utf-8 -*-

"""
Each runtime as a CodeZip: its code directory (``codeLocation``,
``build/agentcore/<Runtime>/``), which ``agentcore deploy`` zips.

The directory mirrors the repo root, so :data:`~agent_app.paths.path_enum`
finds everything where it does locally:

- ``main.py``: a shim that runs the runtime module's ``main()`` (and exposes
  ``app`` for the HTTP runtime).
- ``pyproject.toml``: the project's dependencies, every version pinned from
  ``uv.lock``; the CLI installs only this list.
- ``agent_app/`` without what runs on the developer machine only
  (:data:`EXCLUDED_SUBPACKAGES`), ``data/`` (prompt, SQL policy) and
  ``.env.defaults`` (the committed, non-secret settings).

A build output (git-ignored): the package and ``uv.lock`` stay the sources.
"""

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from ..paths import path_enum
from .settings import RUNTIME_PYTHON

PACKAGE_NAME = path_enum.dir_package.name

#: Subpackages of ``agent_app`` that never ship: this generator, and test helpers.
EXCLUDED_SUBPACKAGES = ("agentcore_project", "tests")

#: The platforms the AgentCore CLI tries, in order, to install a CodeZip's
#: dependencies (``PLATFORM_CANDIDATES`` in ``@aws/agentcore-cdk``).
CODEZIP_PLATFORMS = ("aarch64-manylinux2014", "aarch64-manylinux_2_28", "aarch64-manylinux_2_34")

MAIN_PY = """# Generated by `agent-app ac-gen`; do not edit.
{imports}

if __name__ == "__main__":
    main()
"""


def render_main_py(module: str, is_http: bool) -> str:
    """
    The shim of the runtime module ``module`` (e.g. ``runtimes.analytics_mcp``).
    ``agentcore dev`` serves an HTTP runtime with ``uvicorn main:app``, so its
    shim exposes ``app`` too.
    """
    names = ["main", "app"] if is_http else ["main"]
    imports = "\n".join(f"from {PACKAGE_NAME}.{module} import {name}" for name in names)
    return MAIN_PY.format(imports=imports)


def export_requirements(cwd: Path = path_enum.dir_project_root) -> list[str]:  # pragma: no cover - runs uv
    """
    The project's runtime dependencies with every transitive one, pinned by
    ``uv.lock`` (no test extra, no dev group, not the project itself).
    """
    args = [
        "uv", "export", "--frozen", "--no-dev", "--no-emit-project",
        "--no-hashes", "--no-annotate", "--no-header",
    ]
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True, check=True)
    return parse_requirements(result.stdout)


def parse_requirements(text: str) -> list[str]:
    """
    The requirement lines of ``uv export`` output (comments and blanks dropped).
    """
    lines = (line.strip() for line in text.splitlines())
    return [line for line in lines if line and not line.startswith(("#", "-e"))]


def render_pyproject_toml(name: str, requirements: list[str]) -> str:
    lines = [
        "# Generated by `agent-app ac-gen` from uv.lock; do not edit.",
        "[project]",
        f'name = "{name.lower()}"',
        'version = "0.1.0"',
        f'requires-python = ">={RUNTIME_PYTHON}"',
        "dependencies = [",
        *(f"    {json.dumps(r)}," for r in requirements),  # a JSON string is a TOML basic string
        "]",
    ]
    return "\n".join(lines) + "\n"


def _ignore_package(directory: str, names: list[str]) -> set[str]:
    ignored = {n for n in names if n == "__pycache__" or n.endswith((".pyc", ".duckdb"))}
    if Path(directory) == path_enum.dir_package:
        ignored |= {n for n in names if n in EXCLUDED_SUBPACKAGES}
    return ignored


def assemble_runtime_dir(
    dir_runtime: Path,
    name: str,
    module: str,
    is_http: bool,
    requirements: list[str],
) -> None:
    """
    Write a fresh CodeZip directory for one runtime. Anything else already
    there (the ``.venv`` of ``agentcore dev``) is left alone.
    """
    dir_runtime.mkdir(parents=True, exist_ok=True)
    for sub in (PACKAGE_NAME, "data"):
        shutil.rmtree(dir_runtime / sub, ignore_errors=True)
    shutil.copytree(path_enum.dir_package, dir_runtime / PACKAGE_NAME, ignore=_ignore_package)
    shutil.copytree(path_enum.dir_data, dir_runtime / "data", ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy(path_enum.path_env_defaults, dir_runtime / ".env.defaults")
    (dir_runtime / "main.py").write_text(render_main_py(module, is_http), encoding="utf-8")
    (dir_runtime / "pyproject.toml").write_text(render_pyproject_toml(name, requirements), encoding="utf-8")


def check_codezip_install(path_pyproject_toml: Path) -> str | None:  # pragma: no cover - runs uv
    """
    Resolve a runtime's dependencies the way ``agentcore deploy`` installs
    them (wheels only, Linux aarch64), as a dry run. The CLI reports only
    "uv install failed for all platform candidates"; this keeps uv's message.

    :returns: None if one platform works, else uv's output for the last one.
    """
    output = ""
    for platform in CODEZIP_PLATFORMS:
        with tempfile.TemporaryDirectory() as dir_target:
            args = [
                "uv", "pip", "install", "-r", str(path_pyproject_toml), "--target", dir_target,
                "--python-version", RUNTIME_PYTHON, "--python-platform", platform,
                "--only-binary", ":all:", "--dry-run", "--python", sys.executable,
            ]
            result = subprocess.run(args, capture_output=True, text=True)
        if result.returncode == 0:
            return None
        output = f"{platform}:\n{result.stdout}{result.stderr}"
    return output
